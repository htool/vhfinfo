#!/usr/bin/env node
/**
 * Import data/{CC}.json features into public.vhf_features.
 *
 * Skips *_map.json, *_12Nm.json, countries.json, and countries_bbox.json.
 * Duplicate ids in the same country file are collapsed (last copy wins).
 *
 * Usage:
 *   node scripts/import-vhf-features.js --dry-run
 *   node scripts/import-vhf-features.js --sql > supabase/seed.sql
 *   SUPABASE_SERVICE_ROLE_KEY=... node scripts/import-vhf-features.js
 *
 * Never pass the service_role key to the website. Anon cannot insert these rows.
 */

const fs = require('fs')
const path = require('path')

const ROOT = path.resolve(__dirname, '..')
const DATA_DIR = path.join(ROOT, 'data')
const UUID_RE =
  /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i
const SKIP_FILES = new Set(['countries.json', 'countries_bbox.json'])
const BATCH_SIZE = 40

function parseArgs(argv) {
  const args = { sql: false, dryRun: false, out: null }
  for (let i = 2; i < argv.length; i++) {
    const a = argv[i]
    if (a === '--sql') args.sql = true
    else if (a === '--dry-run') args.dryRun = true
    else if (a === '--out') args.out = argv[++i]
    else {
      console.error('Unknown argument: ' + a)
      process.exit(2)
    }
  }
  return args
}

function shouldSkipFile(name) {
  if (!name.endsWith('.json')) return true
  if (SKIP_FILES.has(name)) return true
  if (name.endsWith('_map.json') || name.endsWith('_12Nm.json')) return true
  return false
}

function countryFromFilename(name) {
  return name.replace(/\.json$/, '')
}

function channelToText(value) {
  if (value == null || value === '') return null
  return String(value)
}

function readPublicSupabaseConfig() {
  const src = fs.readFileSync(
    path.join(ROOT, 'website', 'supabase-config.js'),
    'utf8'
  )
  const url = (src.match(/url:\s*"([^"]+)"/) || [])[1]
  const anonKey = (src.match(/anonKey:\s*"([^"]+)"/) || [])[1]
  return { url, anonKey }
}

function loadRows() {
  const files = fs.readdirSync(DATA_DIR).filter((n) => !shouldSkipFile(n)).sort()
  const byId = new Map()
  const stats = {
    files: files.length,
    seen: 0,
    missingId: 0,
    badId: 0,
    missingGeometry: 0,
    duplicates: 0,
  }

  for (const name of files) {
    const country = countryFromFilename(name)
    const raw = JSON.parse(fs.readFileSync(path.join(DATA_DIR, name), 'utf8'))
    const features = Array.isArray(raw && raw.features) ? raw.features : []
    for (const feature of features) {
      stats.seen += 1
      const props = (feature && feature.properties) || {}
      const id = feature.id || props.id
      if (!id) {
        stats.missingId += 1
        continue
      }
      if (!UUID_RE.test(String(id))) {
        stats.badId += 1
        console.warn('Skip non-uuid id in ' + name + ': ' + id)
        continue
      }
      const geometry = feature.geometry
      if (!geometry || !geometry.type) {
        stats.missingGeometry += 1
        continue
      }
      if (byId.has(id)) stats.duplicates += 1
      byId.set(id, {
        id,
        country,
        name: props.name == null ? null : String(props.name),
        type: props.type == null ? null : String(props.type),
        channel: channelToText(props.channel),
        properties: props,
        geometry,
      })
    }
  }

  return { rows: Array.from(byId.values()), stats }
}

function sqlLiteral(value) {
  if (value == null) return 'null'
  return "'" + String(value).replace(/'/g, "''") + "'"
}

function sqlJsonb(value) {
  return sqlLiteral(JSON.stringify(value)) + '::jsonb'
}

function toSql(rows) {
  const lines = []
  lines.push('-- Generated by scripts/import-vhf-features.js --sql')
  lines.push('-- Idempotent: ON CONFLICT (id) DO UPDATE.')
  lines.push('')
  const chunkSize = 25
  for (let i = 0; i < rows.length; i += chunkSize) {
    const chunk = rows.slice(i, i + chunkSize)
    lines.push('insert into public.vhf_features')
    lines.push('  (id, country, name, type, channel, properties, geometry)')
    lines.push('values')
    chunk.forEach((row, idx) => {
      const comma = idx === chunk.length - 1 ? '' : ','
      lines.push(
        '  (' +
          sqlLiteral(row.id) +
          '::uuid, ' +
          sqlLiteral(row.country) +
          ', ' +
          sqlLiteral(row.name) +
          ', ' +
          sqlLiteral(row.type) +
          ', ' +
          sqlLiteral(row.channel) +
          ', ' +
          sqlJsonb(row.properties) +
          ', ' +
          sqlJsonb(row.geometry) +
          ')' +
          comma
      )
    })
    lines.push('on conflict (id) do update set')
    lines.push('  country = excluded.country,')
    lines.push('  name = excluded.name,')
    lines.push('  type = excluded.type,')
    lines.push('  channel = excluded.channel,')
    lines.push('  properties = excluded.properties,')
    lines.push('  geometry = excluded.geometry;')
    lines.push('')
  }
  lines.push('select country, count(*) as features')
  lines.push('from public.vhf_features')
  lines.push('group by country')
  lines.push('order by features desc, country;')
  lines.push('')
  return lines.join('\n')
}

async function upsertBatch(url, serviceKey, batch) {
  const res = await fetch(url.replace(/\/$/, '') + '/rest/v1/vhf_features', {
    method: 'POST',
    headers: {
      apikey: serviceKey,
      Authorization: 'Bearer ' + serviceKey,
      'Content-Type': 'application/json',
      Prefer: 'resolution=merge-duplicates,return=minimal',
    },
    body: JSON.stringify(batch),
  })
  if (!res.ok) {
    const text = await res.text()
    throw new Error('Upsert failed HTTP ' + res.status + ': ' + text)
  }
}

async function countRows(url, key) {
  const res = await fetch(
    url.replace(/\/$/, '') + '/rest/v1/vhf_features?select=id',
    {
      headers: {
        apikey: key,
        Authorization: 'Bearer ' + key,
        Prefer: 'count=exact',
        Range: '0-0',
      },
    }
  )
  const text = await res.text()
  if (!res.ok) {
    throw new Error('Count failed HTTP ' + res.status + ': ' + text)
  }
  const range = res.headers.get('content-range') || ''
  const total = range.split('/')[1]
  return total == null ? null : Number(total)
}

async function main() {
  const args = parseArgs(process.argv)
  const { rows, stats } = loadRows()
  console.error(
    JSON.stringify(
      {
        countryFiles: stats.files,
        featuresSeen: stats.seen,
        uniqueIds: rows.length,
        duplicatesCollapsed: stats.duplicates,
        missingId: stats.missingId,
        badId: stats.badId,
        missingGeometry: stats.missingGeometry,
      },
      null,
      2
    )
  )

  if (args.dryRun) return

  if (args.sql) {
    const sql = toSql(rows)
    if (args.out) fs.writeFileSync(args.out, sql)
    else process.stdout.write(sql)
    return
  }

  const cfg = readPublicSupabaseConfig()
  const url = process.env.SUPABASE_URL || cfg.url
  const serviceKey = process.env.SUPABASE_SERVICE_ROLE_KEY
  if (!url) {
    console.error('Missing SUPABASE_URL (and website/supabase-config.js).')
    process.exit(1)
  }
  if (!serviceKey) {
    console.error(
      'Set SUPABASE_SERVICE_ROLE_KEY to import via the REST API.\n' +
        'Or generate SQL instead:\n' +
        '  node scripts/import-vhf-features.js --sql --out supabase/seed.sql'
    )
    process.exit(1)
  }

  for (let i = 0; i < rows.length; i += BATCH_SIZE) {
    const batch = rows.slice(i, i + BATCH_SIZE)
    await upsertBatch(url, serviceKey, batch)
    console.error('Upserted ' + Math.min(i + batch.length, rows.length) + '/' + rows.length)
  }

  const total = await countRows(url, serviceKey)
  console.error('vhf_features count: ' + total)
}

main().catch((err) => {
  console.error(err.stack || err.message || err)
  process.exit(1)
})
